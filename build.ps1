$ErrorActionPreference="Stop"
$proj = Split-Path -Parent $MyInvocation.MyCommand.Path
$srcdir = Join-Path $proj "src"
$jsdir = Join-Path $srcdir "js"
$utf8 = New-Object System.Text.UTF8Encoding($false)

# Module load order matters: tools -> data -> roster -> engine -> season -> state
# -> ui-core -> ui-views -> actions -> main -> debug
$order = @(
  "00-tools.js",
  "05-sound.js",
  "10-data.js",
  "20-roster.js",
  "30-engine.js",
  "40-season.js",
  "45-playoff.js",
  "46-history.js",
  "47-records.js",
  "48-draft.js",
  "49-awards.js",
  "50-state.js",
  "60-ui-core.js",
  "70-ui-views.js",
  "80-actions.js",
  "90-main.js",
  "99-debug.js"
)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('"use strict";')
[void]$sb.AppendLine('/* ============================================================')
[void]$sb.AppendLine('   GEKIKUUKAN BASEBALL - bundled output. DO NOT EDIT THIS FILE.')
[void]$sb.AppendLine('   Edit src/js/*.js then run build.ps1 (or double-click build.cmd).')
[void]$sb.AppendLine('   ============================================================ */')
[void]$sb.AppendLine('(function(){')
foreach($f in $order){
  $p = Join-Path $jsdir $f
  if(-not (Test-Path -LiteralPath $p)){ throw ("missing module: " + $f) }
  [void]$sb.AppendLine("/* ===================== " + $f + " ===================== */")
  $code = [System.IO.File]::ReadAllText($p, [System.Text.Encoding]::UTF8)
  [void]$sb.AppendLine($code.TrimEnd())
}
[void]$sb.AppendLine('})();')
$bundle = $sb.ToString()

$tplPath = Join-Path $srcdir "index.template.html"
$tpl = [System.IO.File]::ReadAllText($tplPath, [System.Text.Encoding]::UTF8)
if($tpl.IndexOf('/*__BUNDLE__*/') -lt 0){ throw "template marker /*__BUNDLE__*/ not found" }
$out = $tpl.Replace('/*__BUNDLE__*/', $bundle)

$outName = ([System.IO.File]::ReadAllText((Join-Path $srcdir "outname.txt"), [System.Text.Encoding]::UTF8)).Trim()
$outPath = Join-Path $proj $outName
[System.IO.File]::WriteAllText($outPath, $out, $utf8)

Write-Host ("built -> " + $outName + " (" + $out.Length + " chars)")
